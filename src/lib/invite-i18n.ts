export type Language = "ar" | "en";

const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";
/** Arabic-Indic digits in Arabic, Western digits in English; `pad` zero-pads to two places (countdown). */
export function digits(language: Language, n: number, pad = false) {
  const s = pad ? String(n).padStart(2, "0") : String(n);
  return language === "ar" ? s.replace(/\d/g, (d) => AR_DIGITS[Number(d)] ?? d) : s;
}

